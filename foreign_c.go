package main

// This file holds the C source that ships into every foreign-class
// directory at build time.  Kept in a separate Go file for readability;
// the strings are written verbatim to _st.h / _st_runtime.c by
// BuildForeignClass.

const stHeaderC = `/* auto-generated by servicetalk — do not edit */
#ifndef _ST_H
#define _ST_H

#include <stddef.h>

/* Value — a tagged ServiceTalk value.  C code treats this as opaque and
   uses the helpers below.  The .str field is malloc'd for K_STRING and
   K_OBJID; the runtime does not free values you hand back, so callers
   either reuse incoming args or leak small amounts (fine for most
   microservices). */
typedef struct Value {
    int kind;     /* K_NIL | K_BOOL | K_NUMBER | K_STRING | K_OBJID */
    int len;      /* string/objid length in bytes */
    char* str;    /* string/objid bytes (malloc'd, nul-terminated) */
    double num;
    int boolval;
} Value;

#define K_NIL     0x01
#define K_BOOL    0x02
#define K_NUMBER  0x03
#define K_STRING  0x04
#define K_OBJID   0x05

/* constructors */
Value st_nil(void);
Value st_bool(int truthy);
Value st_number(double d);
Value st_string(const char* bytes, int len);
Value st_cstr(const char* cstr);
Value st_objid(const char* id, int len);

/* predicates */
int st_isNil(Value v);
int st_isString(Value v);
int st_isObject(Value v);
int st_isNumber(Value v);

/* accessors */
const char* st_bytes(Value v, int* len_out);
double      st_asNumber(Value v);

/* send a message to another object.  Blocks until reply arrives. */
Value st_send(Value target, const char* selector, int nargs, Value* args);

/* array helpers; indexes are the same zero-based indexes ServiceTalk uses. */
int   st_arraySize(Value arr);
Value st_arrayAt(Value arr, int index);

/* raise a ServiceTalk signal, unwinding back to whatever (on:do:) handles
   it on the ST side.  Does not return. */
void st_signal(const char* msg);

/* main dispatch loop — call from main() with your class's dispatch fn. */
typedef Value (*st_dispatch_fn)(const char* selector, int nargs, Value* args);
void st_main_loop(st_dispatch_fn dispatch);

#endif
`

const stRuntimeC = `/* auto-generated by servicetalk — do not edit */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <setjmp.h>
#include "_st.h"

#define OP_CALL        0x01
#define OP_RETURN      0x02
#define OP_SEND        0x03
#define OP_SEND_REPLY  0x04
#define OP_SIGNAL      0x05

static FILE* in_f;
static FILE* out_f;

/* On st_signal, longjmp out of the user's dispatch function back to the
   main loop, which writes OP_SIGNAL to the parent and goes on to the next
   call.  Avoids tearing down the whole subprocess on every signal. */
static jmp_buf st_signal_jmp;
static const char* st_pending_signal = NULL;

/* ---- constructors ---- */

Value st_nil(void) {
    Value v;
    v.kind = K_NIL; v.len = 0; v.str = NULL; v.num = 0; v.boolval = 0;
    return v;
}

Value st_bool(int truthy) {
    Value v = st_nil();
    v.kind = K_BOOL;
    v.boolval = truthy ? 1 : 0;
    return v;
}

Value st_number(double d) {
    Value v = st_nil();
    v.kind = K_NUMBER;
    v.num = d;
    return v;
}

Value st_string(const char* bytes, int len) {
    Value v = st_nil();
    v.kind = K_STRING;
    v.len = len;
    v.str = (char*)malloc((size_t)len + 1);
    if (len > 0) memcpy(v.str, bytes, (size_t)len);
    v.str[len] = 0;
    return v;
}

Value st_cstr(const char* cstr) {
    return st_string(cstr, cstr ? (int)strlen(cstr) : 0);
}

Value st_objid(const char* id, int len) {
    Value v = st_string(id, len);
    v.kind = K_OBJID;
    return v;
}

/* ---- predicates / accessors ---- */

int st_isNil(Value v)    { return v.kind == K_NIL; }
int st_isString(Value v) { return v.kind == K_STRING; }
int st_isObject(Value v) { return v.kind == K_OBJID; }
int st_isNumber(Value v) { return v.kind == K_NUMBER; }

const char* st_bytes(Value v, int* len_out) {
    if (len_out) *len_out = v.len;
    return v.str;
}

double st_asNumber(Value v) {
    return v.kind == K_NUMBER ? v.num : 0.0;
}

/* ---- binary IO (matches foreign.go encode/decode) ---- */

static int read_all(FILE* f, void* p, size_t n) {
    return fread(p, 1, n, f) == n;
}

static int read_u32(FILE* f, unsigned int* out) {
    unsigned char b[4];
    if (!read_all(f, b, 4)) return 0;
    *out = (unsigned)b[0]
         | ((unsigned)b[1] << 8)
         | ((unsigned)b[2] << 16)
         | ((unsigned)b[3] << 24);
    return 1;
}

static void write_u32(FILE* f, unsigned int v) {
    unsigned char b[4];
    b[0] = v & 0xFF; b[1] = (v >> 8) & 0xFF;
    b[2] = (v >> 16) & 0xFF; b[3] = (v >> 24) & 0xFF;
    fwrite(b, 1, 4, f);
}

static int read_len_string(FILE* f, char** out, int* len_out) {
    unsigned int n;
    if (!read_u32(f, &n)) return 0;
    char* buf = (char*)malloc((size_t)n + 1);
    if (!buf) return 0;
    if (n > 0 && !read_all(f, buf, n)) { free(buf); return 0; }
    buf[n] = 0;
    *out = buf;
    *len_out = (int)n;
    return 1;
}

static void write_len_string(FILE* f, const char* s, int len) {
    write_u32(f, (unsigned int)len);
    if (len > 0) fwrite(s, 1, (size_t)len, f);
}

static Value read_value(FILE* f) {
    int kind = fgetc(f);
    if (kind == EOF) return st_nil();
    Value v = st_nil();
    v.kind = kind;
    switch (kind) {
        case K_NIL:
            break;
        case K_BOOL:
            v.boolval = fgetc(f) ? 1 : 0;
            break;
        case K_NUMBER: {
            unsigned char b[8];
            read_all(f, b, 8);
            unsigned long long bits = 0;
            for (int i = 0; i < 8; i++) {
                bits |= ((unsigned long long)b[i]) << (i * 8);
            }
            memcpy(&v.num, &bits, 8);
            break;
        }
        case K_STRING:
        case K_OBJID:
            read_len_string(f, &v.str, &v.len);
            break;
        default:
            v = st_nil();
            break;
    }
    return v;
}

static void write_value(FILE* f, Value v) {
    fputc(v.kind, f);
    switch (v.kind) {
        case K_NIL:
            break;
        case K_BOOL:
            fputc(v.boolval ? 1 : 0, f);
            break;
        case K_NUMBER: {
            unsigned long long bits;
            memcpy(&bits, &v.num, 8);
            for (int i = 0; i < 8; i++) {
                fputc((int)((bits >> (i * 8)) & 0xFF), f);
            }
            break;
        }
        case K_STRING:
        case K_OBJID:
            write_len_string(f, v.str ? v.str : "", v.len);
            break;
        default:
            break;
    }
}

/* ---- send + signal (child → parent) ---- */

Value st_send(Value target, const char* selector, int nargs, Value* args) {
    fputc(OP_SEND, out_f);
    write_value(out_f, target);
    write_len_string(out_f, selector, (int)strlen(selector));
    write_u32(out_f, (unsigned int)nargs);
    for (int i = 0; i < nargs; i++) {
        write_value(out_f, args[i]);
    }
    fflush(out_f);

    int op = fgetc(in_f);
    if (op != OP_SEND_REPLY) {
        return st_nil();
    }
    return read_value(in_f);
}

int st_arraySize(Value arr) {
    if (!st_isObject(arr)) return -1;
    Value result = st_send(arr, "size", 0, NULL);
    return st_isNumber(result) ? (int)st_asNumber(result) : -1;
}

Value st_arrayAt(Value arr, int index) {
    if (!st_isObject(arr)) return st_nil();
    Value arg = st_number((double)index);
    return st_send(arr, "at:", 1, &arg);
}

void st_signal(const char* msg) {
    st_pending_signal = msg ? msg : "";
    longjmp(st_signal_jmp, 1);
}

/* ---- main loop ---- */

void st_main_loop(st_dispatch_fn dispatch) {
    in_f = stdin;
    out_f = stdout;

    for (;;) {
        int op = fgetc(in_f);
        if (op == EOF) break;
        if (op != OP_CALL) break;

        char* method = NULL;
        int mlen = 0;
        if (!read_len_string(in_f, &method, &mlen)) break;

        unsigned int nargs;
        if (!read_u32(in_f, &nargs)) { free(method); break; }

        Value* args = NULL;
        if (nargs > 0) {
            args = (Value*)calloc(nargs, sizeof(Value));
            for (unsigned int i = 0; i < nargs; i++) {
                args[i] = read_value(in_f);
            }
        }

        if (setjmp(st_signal_jmp) == 0) {
            Value result = dispatch(method, (int)nargs, args);
            fputc(OP_RETURN, out_f);
            write_value(out_f, result);
        } else {
            fputc(OP_SIGNAL, out_f);
            const char* msg = st_pending_signal ? st_pending_signal : "";
            write_len_string(out_f, msg, (int)strlen(msg));
            st_pending_signal = NULL;
        }
        fflush(out_f);

        free(method);
        free(args);
    }
}
`
