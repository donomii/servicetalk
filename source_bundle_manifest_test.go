func TestGenerationInheritanceUsesOriginalSourcesAfterForeignBuild(t *testing.T) {
 t.Setenv("XDG_CACHE_HOME",t.TempDir())
 files:=[]SourceBundleFile{{Path:"Native/Native.smt",Data:[]byte("(foreign-class Native)")},{Path:"Native/native.c",Data:[]byte("original source")}}
 bundle:=&SourceBundle{Digest:digestSourceBundle(files),Files:files}
 directory,err:=stageSourceBundle(bundle)
 if err!=nil { t.Fatal(err) } else {}
 for _,name:=range []string{"Native/_st.h","Native/_st_glue.c","Native/Cargo.lock","Native/generated.json","Native/Native"} {
  if err:=os.WriteFile(filepath.Join(directory,name),[]byte("generated by foreign build"),0600);err!=nil { t.Fatal(err) } else {}
 }
 t.Setenv("SMT_SOURCE_BUNDLE_DIR",directory)
 inherited:=generationSpawnRequest(SpawnRequest{ClassName:"Helper"}).SourceBundle
 if !reflect.DeepEqual(inherited,bundle) { t.Fatalf("foreign build products changed inherited generation: %+v",inherited) } else {}
 restaged,err:=stageSourceBundle(inherited)
 if err!=nil || restaged!=directory { t.Fatalf("inherit original source: %s, %v",restaged,err) } else {}
}

func TestStagedSourceManifestCannotSilentlyChange(t *testing.T) {
 t.Setenv("XDG_CACHE_HOME",t.TempDir())
 files:=[]SourceBundleFile{{Path:"Original.st",Data:[]byte("class Original []")}}
 bundle:=&SourceBundle{Digest:digestSourceBundle(files),Files:files}
 directory,err:=stageSourceBundle(bundle)
 if err!=nil { t.Fatal(err) } else {}
 path:=filepath.Join(directory,sourceBundleManifestName)
 if err:=os.Remove(path);err!=nil { t.Fatal(err) } else {}
 if _,err:=stageSourceBundle(bundle);err!=nil { t.Fatalf("legacy cache manifest upgrade: %v",err) } else {}
 if err:=os.WriteFile(path,[]byte(`{"digest":"wrong","files":[]}`),0600);err!=nil { t.Fatal(err) } else {}
 if _,err:=stageSourceBundle(bundle);err==nil { t.Fatal("modified source manifest accepted") } else {}
 if _,err:=inheritedSourceBundle(directory);err==nil { t.Fatal("incorrect inherited manifest accepted") } else {}
}

