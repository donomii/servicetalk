#!/bin/sh
# bundle.sh — package a servicetalk app for deployment.
#
# Produces a self-contained directory containing:
#   bin/smt-<os>-<arch>[.exe]  one cross-compiled smt runtime per target
#   <ClassName>.smt            app classes (*.smt + *.st)
#   <ClassName>/               foreign-class directories (copied as-is)
#   run                        POSIX-sh launcher (Linux / macOS)
#   run.cmd                    cmd.exe launcher (Windows)
#   Dockerfile                 alpine wrapper, ENTRYPOINT=/app/run
#
# The launchers iterate the binaries in bin/ and exec the first one
# that responds successfully to the `help` subcommand.  Wrong-arch
# and wrong-OS binaries fail the probe at the kernel exec() boundary,
# so the right binary wins automatically — no `uname` mapping.
#
# At runtime, the smt binary auto-discovers its own location and adds
# the binary's directory, its parent, and parent/Resources to the
# classpath — covering both bundle.sh layouts and macOS .app bundles.
# So `./run` works regardless of the user's current working directory.
#
# Usage:
#   ./bundle.sh APP_DIR [OUT_DIR]
#
# Required:
#   APP_DIR     a directory containing your *.smt / *.st files and any
#               foreign-class subdirectories (see README "Writing an app").
#
# Optional:
#   OUT_DIR     where to write the bundle (default: ${APP_DIR}-bundle).
#               Will be removed and recreated.
#
# Environment:
#   TARGETS     space-separated <goos>/<goarch> list to cross-compile
#               for.  Default:
#                 linux/amd64 linux/arm64
#                 darwin/arm64 darwin/amd64
#                 windows/amd64 windows/arm64
#
# Examples:
#   ./bundle.sh myapp
#   ./bundle.sh myapp dist/myapp
#   TARGETS="linux/amd64 linux/arm64" ./bundle.sh myapp dist/myapp
#
# Next steps:
#   • Run locally:   ./dist/myapp/run coordinator --main Main
#   • Make a Docker image:   docker build -t myapp dist/myapp
#   • Generate a k8s manifest:  ./k8s/bundle.sh dist/myapp REGISTRY/myapp:TAG
#
# Foreign C classes are pre-built per architecture inside the
# Dockerfile via `RUN /app/run prebuild`.  For non-Docker deploys, run
# `./run prebuild` once on each target host (or in a matching-platform
# container, see README "Foreign C classes in the bundle").

set -eu

usage() {
    sed -n '/^# /,/^$/p' "$0" | sed 's/^# \{0,1\}//;s/^#$//'
    exit "${1:-2}"
}

case "${1:-}" in
    -h|--help) usage 0 ;;
esac

APP_DIR="${1:-}"
[ -n "$APP_DIR" ] || usage
APP_DIR="${APP_DIR%/}"
[ -d "$APP_DIR" ] || { echo "bundle.sh: $APP_DIR is not a directory" >&2; exit 1; }

OUT_DIR="${2:-${APP_DIR}-bundle}"
TARGETS="${TARGETS:-linux/amd64 linux/arm64 darwin/arm64 darwin/amd64 windows/amd64 windows/arm64}"

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)

rm -rf "$OUT_DIR"
mkdir -p "$OUT_DIR/bin"
OUT_ABS=$(cd "$OUT_DIR" && pwd)

for tgt in $TARGETS; do
    goos="${tgt%/*}"
    goarch="${tgt#*/}"
    suffix=""
    [ "$goos" = "windows" ] && suffix=".exe"
    bin="$OUT_ABS/bin/smt-${goos}-${goarch}${suffix}"
    echo "→ building $bin"
    ( cd "$SCRIPT_DIR" \
      && CGO_ENABLED=0 GOOS="$goos" GOARCH="$goarch" \
         go build -trimpath -ldflags='-s -w' -o "$bin" . )
done

copied=0
for ext in smt st; do
    for src in "$APP_DIR"/*."$ext"; do
        [ -e "$src" ] || continue
        cp "$src" "$OUT_ABS/"
        copied=$((copied + 1))
    done
done

for dir in "$APP_DIR"/*/; do
    [ -d "$dir" ] || continue
    name=$(basename "$dir")
    [ -f "${dir}${name}.smt" ] || continue
    rm -rf "$OUT_ABS/$name"
    cp -R "$dir" "$OUT_ABS/$name"
    copied=$((copied + 1))
done

if [ "$copied" -eq 0 ]; then
    echo "bundle.sh: no .smt / .st / foreign-class dirs found in $APP_DIR" >&2
    exit 1
fi

cat > "$OUT_ABS/Dockerfile" <<'EODOCKER'
# Generated by bundle.sh.  Wraps this bundle into a runnable image.
#
# Build:
#   docker build -t myapp .
#
# Multi-arch (requires buildx; bundle must contain matching binaries):
#   docker buildx build --platform linux/amd64,linux/arm64 -t myapp .
#
# The `prebuild` step compiles every foreign C class for the image's
# arch during the build, so first-spawn doesn't pay the $CC cost and
# the running container doesn't need a C toolchain at all.  `gcc` and
# `musl-dev` are kept only for the prebuild RUN, then the image runs
# without them — but they only weigh ~50 MB, so we leave them in for
# simplicity.  If your app has no foreign-class directories, drop the
# `apk add` and `prebuild` lines for a smaller image.

FROM alpine:3.19
RUN apk add --no-cache gcc musl-dev
WORKDIR /app
COPY . /app
RUN chmod +x /app/run /app/bin/* 2>/dev/null || true
RUN /app/run prebuild
ENTRYPOINT ["/app/run"]
CMD ["coordinator"]
EODOCKER

cat > "$OUT_ABS/run" <<'EOSH'
#!/bin/sh
# run — launcher for Linux and macOS.
#
# Iterates the binaries in bin/ and exec's the first one that responds
# successfully to `help`.  Wrong-arch / wrong-OS binaries fail the probe
# (the kernel returns an exec error), so the right binary wins without
# needing to inspect `uname`.
#
# The smt binary itself auto-discovers its bundle directory from its
# own location, so this script does not need to cd or set --path; the
# user's CWD is preserved.

set -eu

DIR=$(cd "$(dirname "$0")" && pwd)
BINDIR="$DIR/bin"

found=
for bin in "$BINDIR"/smt-*; do
    [ -f "$bin" ] || continue
    case "$bin" in *.exe) continue ;; esac
    [ -x "$bin" ] || continue
    if "$bin" help >/dev/null 2>&1; then
        found="$bin"
        break
    fi
done

if [ -z "$found" ]; then
    echo "run: no compatible smt binary in $BINDIR" >&2
    echo "available:" >&2
    ls "$BINDIR" >&2 || true
    exit 1
fi

exec "$found" "$@"
EOSH
chmod +x "$OUT_ABS/run"

cat > "$OUT_ABS/run.cmd" <<'EOCMD'
@echo off
rem run.cmd — launcher for Windows.
rem
rem Iterates the .exe binaries in bin\ and runs the first one that
rem responds successfully to `help`.  Wrong-arch binaries fail the
rem probe, so the right binary wins.

setlocal enabledelayedexpansion
set "DIR=%~dp0"
set "BINDIR=%DIR%bin"

for %%b in ("%BINDIR%\smt-*.exe") do (
    "%%b" help >nul 2>&1
    if !errorlevel! equ 0 (
        "%%b" %*
        exit /b !errorlevel!
    )
)

echo run.cmd: no compatible smt binary in %BINDIR% 1>&2
exit /b 1
EOCMD

echo "done: $OUT_DIR"
